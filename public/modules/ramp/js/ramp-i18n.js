// Traduire une clé dans la langue courante du module. Les trous {0}, {1}… sont
// remplacés par les arguments, dans l'ordre.
function rt(cle, ...args) {
    const lang = (typeof RAMP_STATE !== 'undefined' && RAMP_STATE.lang) || 'fr';
    const dico = RAMP_TR[lang] || RAMP_TR.fr;
    let texte = dico[cle] || RAMP_TR.fr[cle] || cle;
    args.forEach((a, i) => { texte = texte.split(`{${i}}`).join(a); });
    return texte;
}

// Le pluriel se dit d'une langue à l'autre : on choisit la forme sur le nombre.
const rtn = (n, cleUn, clePlusieurs) => rt(Number(n) > 1 ? clePlusieurs : cleUn);

Object.assign(window, { RAMP_TR, rt, rtn });
