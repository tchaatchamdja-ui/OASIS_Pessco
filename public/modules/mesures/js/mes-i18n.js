// Traduction d'une clé, avec textes à trou : mt('kpi_visees', 3).
function mt(cle, ...valeurs) {
  const langue = (typeof MES_STATE !== 'undefined' && MES_STATE.lang) || 'fr';
  const table = MES_TR[langue] || MES_TR.fr;
  const texte = table[cle] !== undefined ? table[cle]
    : (MES_TR.fr[cle] !== undefined ? MES_TR.fr[cle] : cle);
  return valeurs.reduce((t, v, i) => t.split(`{${i}}`).join(String(v)), texte);
}
