/**
 * L'appel d'API de l'application.
 *
 * Deux en-têtes posés systématiquement, et `X-OASIS-Request` n'est pas
 * décoratif : le serveur refuse une écriture qui ne le porte pas
 * (`403 origine_non_reconnue`).
 *
 * Un 401 ne lève pas seulement : il ramène à la connexion. Et le message d'un
 * refus est **traduit par le socle**, non recopié du serveur — les deux ont
 * divergé, et c'est pourquoi `oasisMessageErreur` existe.
 */
export async function api(chemin: string, options: RequestInit = {}): Promise<unknown> {
  const jeton = localStorage.getItem('pr_token');
  const entetes: Record<string, string> = {
    'Content-Type': 'application/json',
    'X-OASIS-Request': '1',
    ...(jeton ? { Authorization: `Bearer ${jeton}` } : {}),
  };
  const res = await fetch(chemin, {
    ...options,
    headers: { ...entetes, ...(options.headers as Record<string, string> | undefined) },
  });
  if (res.status === 401) {
    window.oasisSessionPerdue();
    throw new Error(window.oasisMessageErreur({ error: 'unauthenticated' }, res.status));
  }
  const donnees: unknown = await res.json();
  if (!res.ok) throw new Error(window.oasisMessageErreur(donnees, res.status));
  return donnees;
}
