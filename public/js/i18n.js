const LANG_KEY = 'pr_lang';
let CURRENT_LANG = localStorage.getItem(LANG_KEY) || 'fr';

// Les arguments comblent {0}, {1}… — même convention que les dictionnaires des
// modules, pour que la place du nom dans la phrase suive la langue.
function t(key, ...args) {
  let s = (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]) || I18N.fr[key] || key;
  args.forEach((v, i) => { s = s.replace(`{${i}}`, v); });
  return s;
}

function applyLang(lang) {
  CURRENT_LANG = I18N[lang] ? lang : 'fr';
  localStorage.setItem(LANG_KEY, CURRENT_LANG);
  document.documentElement.lang = CURRENT_LANG;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('.lang-btn').forEach((b) => {
    b.classList.toggle('active', b.textContent.trim().toLowerCase() === CURRENT_LANG);
  });
  if (typeof window.onLangChange === 'function') window.onLangChange();
}

